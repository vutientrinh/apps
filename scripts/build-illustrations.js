// Turns apps/assets/illustrations/*.svg into src/ui/illustration-xml.ts (Metro cannot import .svg as text).
// Run `npm run illustrations` after adding or changing an SVG; src/ui/illustration.test.tsx fails if you forget.
const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const sourceDir = path.join(root, 'assets', 'illustrations');
const target = path.join(root, 'src', 'ui', 'illustration-xml.ts');

/** `style="fill:X;stroke:Y"` → `fill="X" stroke="Y"` (the style wins over an attribute, as in a browser). */
function inlineStyles(svg) {
  return svg.replace(/<[a-zA-Z][^>]*\sstyle="[^"]*"[^>]*>/g, (tag) => {
    const style = /\sstyle="([^"]*)"/.exec(tag)[1];
    let next = tag.replace(/\sstyle="[^"]*"/, '');
    const attributes = [];
    for (const declaration of style.split(';')) {
      const [property, value] = declaration.split(':').map((part) => part?.trim());
      if (property !== 'fill' && property !== 'stroke') continue;
      next = next.replace(new RegExp(`\\s${property}="[^"]*"`), '');
      attributes.push(`${property}="${value}"`);
    }
    if (!attributes.length) return next;
    return next.replace(/^<([a-zA-Z]+)/, `<$1 ${attributes.join(' ')}`);
  });
}

function buildModule() {
  const files = fs.readdirSync(sourceDir).filter((file) => file.endsWith('.svg')).sort();
  const entries = files.map((file) => {
    const svg = fs.readFileSync(path.join(sourceDir, file), 'utf8').trim().replace(/\s(aria-hidden|focusable)="[^"]*"/g, '');
    return `  '${file.replace(/\.svg$/, '')}':\n    ${JSON.stringify(inlineStyles(svg))},`;
  });
  return [
    '// GENERATED by scripts/build-illustrations.mjs from assets/illustrations/*.svg. Do not edit.',
    '// unDraw scenes (https://undraw.co/license), themed with `var(--token)` placeholders. See docs/design/assets.md.',
    'export const illustrationXml = {',
    ...entries,
    '} as const;',
    '',
  ].join('\n');
}

if (require.main === module) {
  fs.writeFileSync(target, buildModule());
  console.log(`Wrote ${path.relative(root, target)}`);
}

module.exports = { inlineStyles, buildModule };
